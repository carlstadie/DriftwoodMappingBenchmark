# ----------------------------
# PALETTE
# tab20 is organised as 10 dark/light pairs (indices 0/1, 2/3, 4/5, …).
# We pick one DARK anchor per sensor from tab20, then derive three shades
# by blending toward white:
#   training   → 0 % white blend  (darkest  — most data, most prominent)
#   validation → 45 % white blend (medium)
#   testing    → 72 % white blend (lightest)
#
# Sensor → tab20 index for the DARK anchor:
#   AE → 0  (blue)
#   PS → 2  (orange)
#   S2 → 4  (green)
# ----------------------------
_tab20 = plt.cm.tab20.colors

SENSOR_BASE_IDX = {"AE": 0, "PS": 2, "S2": 4}   # tab20 dark anchors
SPLIT_BLEND     = {                               # fraction blended toward white
    "training":   0.00,
    "validation": 0.45,
    "testing":    0.72,
}
BOX_ALPHA = 0.90

PANEL_ORDER = ["AE", "PS", "S2"]
SPLIT_ORDER = ["training", "validation", "testing"]


def _blend_to_white(rgb, fraction):
    """Linearly interpolate rgb toward white by `fraction` (0=original, 1=white)."""
    r, g, b = rgb
    return (
        r + (1 - r) * fraction,
        g + (1 - g) * fraction,
        b + (1 - b) * fraction,
    )


def get_split_color(sensor: str, split_name: str) -> tuple:
    """Return an RGB tuple for the given sensor × split combination."""
    base_idx = SENSOR_BASE_IDX.get(sensor, 0)
    base_rgb = _tab20[base_idx][:3]           # strip alpha if present
    blend    = SPLIT_BLEND.get(split_name, 0.0)
    return _blend_to_white(base_rgb, blend)


def get_sensor_mid_color(sensor: str) -> tuple:
    """Middle (validation) shade — used for the legend patch."""
    return get_split_color(sensor, "validation")


