def safe_read_labels(path: str, source: str) -> Optional[gpd.GeoDataFrame]:
    if path is None or str(path).strip() == "":
        return None
    try:
        gdf = gpd.read_file(path)
        if gdf is None or len(gdf) == 0:
            return None
        gdf = gdf.copy()
        gdf["source"] = source
        return gdf
    except Exception as e:
        print(f"[WARN] Could not read {source} labels from: {path}\n       {e}")
        return None


def make_valid(gdf: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    gdf = gdf.copy()
    try:
        gdf["geometry"] = gdf.geometry.make_valid()
    except Exception:
        pass
    return gdf


def decade_math_formatter(y, _):
    k = int(np.round(y))
    if np.isfinite(y) and abs(y - k) < 1e-6:
        return rf"$10^{{{k}}}$"
    return ""


def apply_axes_style(ax):
    for side in ["left", "right", "top", "bottom"]:
        ax.spines[side].set_visible(True)
        ax.spines[side].set_linewidth(0.7)
        ax.spines[side].set_color("#333333")
    ax.tick_params(axis="x", labelsize=7, pad=2, bottom=True, top=False,
                   labelbottom=True, direction="out", length=3, width=0.7)
    ax.tick_params(axis="y", labelsize=7, pad=2, left=True, right=False,
                   labelleft=True, direction="out", length=3, width=0.7)
    ax.grid(axis="y", alpha=0.18, linestyle="--", linewidth=0.4)
    ax.set_axisbelow(True)
    ax.margins(x=0.02)


def _maybe_downsample(vals: np.ndarray, max_n: Optional[int]) -> np.ndarray:
    if max_n is None or len(vals) <= max_n:
        return vals
    idx = RNG.choice(len(vals), size=max_n, replace=False)
    return vals[idx]


def empty_panel(ax, title: str, ns: List[int], ylabel: Optional[str] = None):
    ax.set_title(title, fontsize=8, fontweight="bold", pad=6)
    if ylabel:
        ax.set_ylabel(ylabel, fontsize=7)
    ax.set_xticks([1, 2, 3])
    ax.set_xticklabels(["train", "val", "test"])
    ax.set_xlim(0.5, 3.5)
    trans = blended_transform_factory(ax.transData, ax.transAxes)
    for i, n in enumerate(ns, start=1):
        ax.text(i, TEXTOFF, f"n={n}", transform=trans, ha="center", va="bottom",
                fontsize=6, clip_on=False)
    apply_axes_style(ax)
    ax.text(0.5, 0.5, "No data", transform=ax.transAxes,
            ha="center", va="center", alpha=0.6)


def colored_boxplot_with_points(
    ax,
    data_by_split: Dict[str, np.ndarray],
    split_order: List[str],
    sensor: str,
    title: str,
    ylabel: Optional[str] = None,
    ns: Optional[List[int]] = None,
    points: bool = True,
):
    data   = [data_by_split.get(sp, np.array([])) for sp in split_order]
    labels = ["train", "val", "test"]

    bp = ax.boxplot(
        data,
        labels=labels,
        patch_artist=True,
        vert=True,
        showfliers=True,
        flierprops=dict(marker=".", markersize=2, markerfacecolor="none",
                        markeredgecolor="#555555", markeredgewidth=0.4, alpha=0.5),
        widths=0.55,
    )

    ax.set_xticks(np.arange(1, 4))
    ax.set_xlim(0.5, 3.5)

    # Each split box gets its own shade of the sensor's hue
    for box, split_name in zip(bp["boxes"], split_order):
        color = get_split_color(sensor, split_name)
        box.set_facecolor(color)
        box.set_edgecolor("black")
        box.set_linewidth(0.7)
        box.set_alpha(BOX_ALPHA)

    for line in bp["whiskers"]:
        line.set_color("black"); line.set_linewidth(0.7)
    for line in bp["caps"]:
        line.set_color("black"); line.set_linewidth(0.7)
    for line in bp["medians"]:
        line.set_color("black"); line.set_linewidth(1.2)

    if points:
        for i, sp in enumerate(split_order, start=1):
            vals = data_by_split.get(sp, np.array([]))
            if vals is None or len(vals) == 0:
                continue
            vals_plot = _maybe_downsample(vals, MAX_POINTS_PER_SPLIT)
            x_pos = RNG.normal(loc=i, scale=JITTER_SD, size=len(vals_plot))
            big   = len(vals_plot) > 1200
            ax.scatter(
                x_pos, vals_plot,
                alpha=POINT_ALPHA_BIG if big else POINT_ALPHA_SMALL,
                s=POINT_SIZE_BIG if big else POINT_SIZE_SMALL,
                color=get_split_color(sensor, sp),
                edgecolors=POINT_EDGE_COLOR,
                linewidth=POINT_EDGE_LW,
                zorder=3,
                rasterized=True,
            )

    ax.set_title(title, fontsize=8, fontweight="bold", pad=6)
    ax.set_xlabel("")
    ax.set_ylabel(ylabel if ylabel else "", fontsize=7)
    apply_axes_style(ax)

    if ns is not None:
        trans = blended_transform_factory(ax.transData, ax.transAxes)
        for i, n in enumerate(ns, start=1):
            ax.text(i, TEXTOFF, f"n={n}", transform=trans, ha="center", va="bottom",
                    fontsize=6, clip_on=False)


# ----------------------------
# Legend handler: original mini boxplot
# ----------------------------
class BoxplotHandler(HandlerBase):
    def create_artists(self, legend, orig_handle, xdescent, ydescent,
                       width, height, fontsize, trans):
        box_w = width * 0.6
        box_h = height * 0.5
        xc    = xdescent + width / 2
        yc    = ydescent + height / 2

        box = Rectangle(
            (xc - box_w / 2, yc - box_h / 2), box_w, box_h,
            facecolor=orig_handle.get_facecolor(),
            edgecolor="black",
            linewidth=0.7,
            alpha=BOX_ALPHA,
            transform=trans,
        )
        median = Line2D(
            [xc - box_w / 2, xc + box_w / 2], [yc, yc],
            color="black", linewidth=1.2, transform=trans,
        )
        wt = Line2D(
            [xc, xc], [yc + box_h / 2, yc + box_h / 2 + height * 0.15],
            color="black", linewidth=0.7, transform=trans,
        )
        wb = Line2D(
            [xc, xc], [yc - box_h / 2, yc - box_h / 2 - height * 0.15],
            color="black", linewidth=0.7, transform=trans,
        )
        return [box, median, wt, wb]


